//! Regenerate the current corpus and golden IDs with `--write`.
//! `--rare` searches reproducible Expert seeds without third-party puzzles.
use pencil_puzzles_sudoku::*;
use std::{fs, path::Path};
fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..");
    let write = std::env::args().any(|s| s == "--write");
    let rare = std::env::args().any(|s| s == "--rare");
    let mut cases = vec![
        ("smallest", "1x1", Difficulty::Easy, 0),
        ("small", "4x4", Difficulty::Easy, 0),
        ("easy", "9x9", Difficulty::Easy, 0),
        ("medium", "9x9", Difficulty::Medium, 0),
        ("hard", "9x9", Difficulty::Hard, 0),
        // Pins the Expert search (clues put back into the best candidate).
        ("expert", "9x9", Difficulty::Expert, 0),
    ];
    if rare {
        for (name, level) in [("expert", Difficulty::Expert)] {
            for seed in 0..30 {
                let mut options = GenerateOptions::new("9x9".parse().unwrap(), seed);
                options.difficulty = Some(level);
                options.max_attempts = 2000;
                if let Ok(g) = generate(&options, &Budget::new(1_000_000)) {
                    println!(
                        "found {name} at seed {seed}: {} ({} attempts)",
                        g.puzzle.id(),
                        g.attempts
                    );
                    cases.push((name, "9x9", level, seed));
                    break;
                }
                if seed % 5 == 0 {
                    println!("search {name}: seed {seed}");
                }
            }
        }
    }
    let mut golden = String::from("# params difficulty seed id generator_version\n");
    for (name, shape, level, seed) in cases {
        let mut options = GenerateOptions::new(shape.parse().unwrap(), seed);
        options.difficulty = Some(level);
        let g = generate(&options, &Budget::new(100_000_000)).unwrap();
        let mut record = Record::new(g.puzzle.clone());
        record.solution = Some(g.solution);
        record.shared.source = Some("Generated by pencil-puzzles".into());
        record.shared.license = Some("MIT".into());
        record.shared.params = Some(shape.into());
        record.shared.difficulty = Some(level);
        record.shared.seed = Some(seed);
        record.shared.generator_version = Some(g.generator_version);
        record.shared.rater_version = Some(g.rating.rater_version);
        record.shared.rating = Some((g.rating.level, g.rating.score));
        golden.push_str(&format!(
            "{shape} {level} {seed} {} {}\n",
            g.puzzle.id(),
            g.generator_version
        ));
        println!("{name}: {} {:?}", g.puzzle.id(), g.rating);
        if write {
            fs::create_dir_all(root.join("corpus/sudoku")).unwrap();
            fs::write(
                root.join(format!("corpus/sudoku/{name}.txt")),
                write_record(&record) + "\n",
            )
            .unwrap();
        }
    }
    if write {
        fs::write(root.join("crates/genres/sudoku/tests/golden.txt"), golden).unwrap();
    }
}
