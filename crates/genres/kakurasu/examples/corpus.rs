//! Regenerate C1–C4 fixtures and T4 golden puzzles with `cargo run --release
//! -p pencil-puzzles-kakurasu --example corpus -- --write`.
use pencil_puzzles_kakurasu::*;
use std::{fs, path::Path};
fn main() {
    let write = std::env::args().any(|arg| arg == "--write");
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..");
    let mut golden = String::from("# params difficulty seed id generator_version\n");
    for (name, shape, level) in [
        ("smallest", "1x1", Difficulty::Easy),
        ("line", "1x7", Difficulty::Easy),
        ("rectangle", "3x5", Difficulty::Easy),
        ("medium", "6x6", Difficulty::Medium),
        ("hard", "7x7", Difficulty::Hard),
        ("expert", "8x8", Difficulty::Expert),
    ] {
        let mut options = GenerateOptions::new(shape.parse().unwrap(), 0);
        options.difficulty = Some(level);
        let g = generate(&options, &Budget::new(500_000_000)).unwrap();
        let mut record = Record::new(g.puzzle.clone());
        record.solution = Some(g.solution);
        record.shared.source = Some("Generated by pencil-puzzles".into());
        record.shared.license = Some("MIT".into());
        record.shared.params = Some(shape.into());
        record.shared.difficulty = Some(level);
        record.shared.seed = Some(g.seed);
        record.shared.generator_version = Some(g.generator_version);
        record.shared.rater_version = Some(g.rating.rater_version);
        record.shared.rating = Some((g.rating.level, g.rating.score));
        golden.push_str(&format!(
            "{shape} {level} {} {} {}\n",
            g.seed,
            g.puzzle.id(),
            g.generator_version
        ));
        println!(
            "{name}: {} {:?}, attempts {}",
            g.puzzle.id(),
            g.rating,
            g.attempts
        );
        if write {
            fs::create_dir_all(root.join("corpus/kakurasu")).unwrap();
            fs::write(
                root.join(format!("corpus/kakurasu/{name}.txt")),
                write_record(&record) + "\n",
            )
            .unwrap();
        }
    }
    if write {
        fs::write(root.join("crates/genres/kakurasu/tests/golden.txt"), golden).unwrap();
    }
}
